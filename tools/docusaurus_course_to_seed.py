def read_text_lf(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\r", "\n")


def url_filename(url: str) -> str:
    """URL -> 本地文件名：去查询串与锚点取最后段，非法字符转 _。"""
    no_frag = url.split("#", 1)[0]
    no_query = no_frag.split("?", 1)[0]
    last = no_query.rstrip("/").rsplit("/", 1)[-1]
    name = ILLEGAL_FN_RE.sub("_", last) or "image"
    return name


def normalize_iframe_url(src: str) -> str:
    """iframe src -> 可读 URL：bvid 参数规范化为 bilibili 视频页，否则补协议。"""
    m = re.search(r"[?&]bvid=(BV[0-9A-Za-z]+)", src)
    if m:
        return f"https://www.bilibili.com/video/{m.group(1)}"
    if src.startswith("//"):
        return "https:" + src
    if src.startswith("https://") or src.startswith("http://"):
        return src
    return "https:" + src


def split_code_spans(line: str):
    """把一行切成 [code内/outside] 交替片段；只对 outside 段做行内变换。"""
    parts = line.split("`")
    return parts


