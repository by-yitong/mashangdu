class Converter:
    """单章 mdx 转换器（一次运行共用实例，聚合告警）。"""

    def __init__(self, collector: ImageCollector):
        self.collector = collector
        self.warnings = []

    def warn(self, page: str, msg: str):
        self.warnings.append(f"[{page}] {msg}")

    # ---- frontmatter / 标题 ----

    @staticmethod
    def extract_frontmatter(text: str):
        m = FRONTMATTER_RE.match(text)
        if not m:
            return text, None
        body = text[m.end():]
        tm = FM_TITLE_RE.search(m.group(1))
        title = tm.group(1).strip() if tm else None
        if title:
            title = " ".join(title.split())
        return body, title

    @staticmethod
    def first_h1(lines):
        inf = False
        for ln in lines:
            if FENCE_RE.match(ln):
                inf = not inf
                continue
            if not inf and re.match(r"^#\s+\S", ln):
                return re.sub(r"^#\s+", "", ln).strip()
        return ""

    # ---- 主转换：行级状态机，递归处理嵌套结构 ----

    def convert(self, text: str, page: str, chapter: str, var_map: dict) -> list:
        lines = text.split("\n")
        out = []
        i, n = 0, len(lines)
        while i < n:
            line = lines[i]

            # --- 代码围栏：开行按规则 11 规范化语言标注，内容与闭行原样保留 ---
            if FENCE_RE.match(line):
                j = i + 1
                while j < n and not FENCE_RE.match(lines[j]):
                    j += 1
                body = lines[i + 1:j]
                out.append(self._fence_open(line, body))
                out.extend(body)
                if j < n:
                    out.append(lines[j])
                i = j + 1
                continue

            # --- Docusaurus 警告框 -> 块引用 ---
            m = ADMON_OPEN_RE.match(line)
            if m:
                body, i = self._collect_admonition(lines, i, page)
                conv = self._convert_block(body, page, chapter, var_map)
                while conv and not conv[0].strip():
                    conv.pop(0)
                while conv and not conv[-1].strip():
                    conv.pop()
                if conv:
                    out.append("")
                    title = m.group(2) or TYPE_CN.get(m.group(1), m.group(1))
                    out.append(f"> **{title}**")
                    out.extend(("> " + ln).rstrip() if ln.strip() else ">" for ln in conv)
                    out.append("")
                continue

            # --- Tabs / TabItem ---
            if re.match(r"^<Tabs\b", line, re.I) or re.match(r"^</Tabs>\s*$", line, re.I):
                i += 1
                continue
            if re.match(r"^</TabItem>\s*$", line, re.I):
                i += 1
                continue
            m = TABITEM_OPEN_RE.match(line)
            if m:
                body = []
                i += 1
                while i < n and not re.match(r"^</TabItem>\s*$", lines[i], re.I):
                    body.append(lines[i][2:] if lines[i].startswith("  ") else lines[i])
                    i += 1
                i += 1  # 跳过 </TabItem>
                conv = self._convert_block(body, page, chapter, var_map)
                while conv and not conv[0].strip():
                    conv.pop(0)
                while conv and not conv[-1].strip():
                    conv.pop()
                out.append("")
                out.append(f"**{m.group(1)}**")
                out.append("")
                out.extend(conv)
                out.append("")
                continue

            # --- iframe -> 视频引用行 ---
            m = IFRAME_RE.search(line)
            if m:
                out.append(f"> 🎬 在线视频：[观看]({normalize_iframe_url(m.group(1))})")
                i += 1
                continue

            # --- div 包装：删除标签行本身 ---
            stripped = line.strip()
            if re.match(r"^<div\b[^>]*>$", stripped, re.I) or stripped == "</div>":
                i += 1
                continue

            # --- 其余行内变换 ---
            out.extend(self._transform_line(line, page, chapter, var_map))
            i += 1
        return out

    def _convert_block(self, body_lines, page, chapter, var_map):
        return self.convert("\n".join(body_lines), page, chapter, var_map)

    def _collect_admonition(self, lines, start, page):
        """收集 :::type 行到配对 ::: 之间的正文（围栏感知）；返回 (body, 下一下标)。"""
        n = len(lines)
        body = []
        inf = False
        i = start + 1
        while i < n:
            ln = lines[i]
            if FENCE_RE.match(ln):
                inf = not inf
                body.append(ln)
                i += 1
                continue
            if not inf and ln.strip() == ":::":
                return body, i + 1
            body.append(ln)
            i += 1
        self.warn(page, "警告框缺少闭合 ::: ，按文件尾处理")
        return body, i

    @staticmethod
    def _fence_open(line: str, body) -> str:
        """规则 11：围栏开行语言标注规范化（闭行与内容不动，其余围栏字节不变）。

        Docusaurus 的 title="..." 等属性后缀必须删除——App 端把整个 info string
        当语言名做高亮匹配，带属性会整串失效；只保留首个语言 token。"""
        rest = line[3:].strip()
        if rest == "":
            content = "\n".join(body)
            lang = "groovy" if any(k in content for k in GROOVY_MARKERS) else "kotlin"
            return "```" + lang
        lang = rest.split()[0]
        if lang in ("Kotlin", "undefined"):
            lang = "kotlin"
        return "```" + lang

    # ---- 行内变换（图片 / HTML / 残留） ----

    def _transform_line(self, line: str, page: str, chapter: str, var_map: dict):
        # 整行仅为一个 <img> 标签（div 包装内常见带缩进）：转换后顶格输出，
        # 避免残留缩进被 Markdown 渲染成代码块
        stripped = line.strip()
        if stripped.startswith("<img"):
            tm = IMG_TAG_RE.match(stripped)
            if tm and tm.end() == len(stripped):
                converted = self._md_images(stripped, page, chapter, var_map)
                converted = self._inline(converted, page, chapter, var_map)
                return [converted]

        # <br> -> 空行分段（先行处理，避免行内替换破坏结构）
        if BR_RE.search(line):
            segs = BR_RE.split(line)
            head = segs[0].rstrip()
            out = [head] if (head or len(segs) == 1) else []
            for seg in segs[1:]:
                tail = seg.strip()
                if tail:
                    out.append("")
                    out.append(tail)
            if not out:
                out = [""]
            return [self._inline(self._md_images(ln, page, chapter, var_map),
                                 page, chapter, var_map) for ln in out]

        line = self._md_images(line, page, chapter, var_map)
        return [self._inline(line, page, chapter, var_map)]

    def _md_images(self, line: str, page: str, chapter: str, var_map: dict) -> str:
        """图片转换：JSX <img> 与 markdown 外链图片 -> 本地相对路径。"""

        def repl_tag(m):
            tag = m.group(0)
            mv = IMG_SRC_VAR_RE.search(tag)
            if mv:
                var = mv.group(1)
                path = var_map.get(var)
                if path is None:
                    self.warn(page, f"<img> 引用了未 import 的变量 {{{var}}}，标签已删除")
                    return ""
                rel = self.collector.plan_copy(page, chapter, path, var)
                if rel is None:
                    self.warn(page, f"缺失图片 static/{path}，已用占位行替代")
                    return f"> [缺失图片: {path}]"
                return f"![]({rel})"
            mu = IMG_SRC_URL_RE.search(tag)
            if mu and (mu.group(1).startswith("http") or mu.group(1).startswith("//")):
                url = mu.group(1)
                if url.startswith("//"):
                    url = "https:" + url
                rel = self.collector.plan_download(chapter, url)
                return f"![]({rel})"
            if mu:  # 相对路径 src：本书未出现，保留并告警
                self.warn(page, f"未知 <img> src 形式，标签已删除: {tag[:80]}")
            return ""

        line = IMG_TAG_RE.sub(repl_tag, line)

        def repl_md(m):
            url = m.group(2)
            rel = self.collector.plan_download(chapter, url)
            return f"![{m.group(1)}]({rel})"

        return MD_EXT_IMG_RE.sub(repl_md, line)

    def _inline(self, line: str, page: str, chapter: str, var_map: dict) -> str:
        """行内 HTML 清理 + 残留 JSX 扫描（反引号代码段内不动）。"""
        line = COMMENT_RE.sub("", line)
        line = CODE_TAG_RE.sub(lambda m: "`" + m.group(1) + "`", line)
        line = re.sub(r"</?b>", "**", line)
        line = re.sub(r"</?(?:i|em)>", "*", line)
        line = re.sub(r"</?(?:u|center)>", "", line)

        # 残留 {标识符} / <大写标签>：只在反引号代码段之外处理
        parts = line.split("`")
        for idx in range(0, len(parts), 2):
            seg = parts[idx]

            def repl_brace(m):
                self.warn(page, f"删除残留 MDX 表达式 {{{m.group(1)}}}")
                return ""

            seg = RESIDUAL_BRACE_RE.sub(repl_brace, seg)

            def repl_tag(m):
                if m.group(2) is None:  # <Word>：正文中的 Kotlin 泛型，包反引号
                    return f"`{m.group(0)}`"
                self.warn(page, f"删除残留 JSX 标签 {m.group(0)[:80]}")
                return ""

            seg = RESIDUAL_TAG_RE.sub(repl_tag, seg)
            parts[idx] = seg
        return "`".join(parts)

    # ---- 收尾 ----

    @staticmethod
    def tidy(lines):
        while lines and not lines[0].strip():
            lines.pop(0)
        while lines and not lines[-1].strip():
            lines.pop()
        out = []
        blanks = 0
        for ln in lines:
            if ln.strip() == "":
                blanks += 1
                if blanks > 2:
                    continue
            else:
                blanks = 0
            out.append(ln)
        return out


