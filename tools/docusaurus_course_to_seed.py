def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Docusaurus 教程仓库转 seed 格式（详见文件头注释）")
    p.add_argument("--repo", default=str(Path.home() / "AppData/Local/Temp/jetpack-compose-book"),
                   help="jetpack-compose-book 本地 clone 路径（含 docs/ 与 static/）")
    p.add_argument("--docs-dir", default="docs", help="clone 内文档源目录")
    p.add_argument("--course-slug", default=DEFAULT_COURSE_SLUG, help="课程 slug")
    p.add_argument("--course-title", default=DEFAULT_COURSE_TITLE, help="课程标题")
    p.add_argument("--summary", default=DEFAULT_SUMMARY, help="课程简介")
    p.add_argument("--language", default=DEFAULT_LANGUAGE, help="课程语言标注")
    p.add_argument("--color", default=DEFAULT_COLOR, help="课程主题色")
    p.add_argument("--sort-order", type=int, default=DEFAULT_SORT_ORDER, help="课程 sort_order")
    p.add_argument("--images-dir", default="backend/static/images", help="图片输出根目录")
    p.add_argument("--out", default="backend/internal/store/seeddata", help="seeddata 输出目录")
    p.add_argument("--limit", type=int, default=0, help="只转换前 N 章（调试用，0=全部）")
    p.add_argument("--timeout", type=int, default=30, help="HTTP 超时秒数")
    p.add_argument("--retries", type=int, default=2, help="HTTP 失败重试次数")
    return p


def main(argv=None) -> int:
    args = build_arg_parser().parse_args(argv)
    repo = Path(args.repo)
    docs = repo / args.docs_dir
    if not docs.is_dir():
        sys.exit(f"源仓库不存在：{docs}（先 git clone --depth 1 "
                 "https://github.com/compose-museum/jetpack-compose-book）")

    spec = CHAPTER_SPEC[: args.limit] if args.limit else CHAPTER_SPEC
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    collector = ImageCollector(repo, Path(args.images_dir), args.course_slug,
                               retries=args.retries, timeout=args.timeout)
    conv = Converter(collector)

    chapters = []
    entries = []  # (slug, title, content)
    slugs_seen = set()
    for idx, (rel, slug) in enumerate(spec, start=1):
        if slug in slugs_seen:
            sys.exit(f"slug 重复: {slug}")
        slugs_seen.add(slug)
        src = docs / rel
        if not src.is_file():
            sys.exit(f"源文件缺失: {src}")
        text = read_text_lf(src)
        body, fm_title = conv.extract_frontmatter(text)
        title = fm_title or conv.first_h1(body.split("\n"))
        if not title:
            sys.exit(f"取不到标题（frontmatter 无 title 且正文无 H1）: {rel}")

        # import 行：@site/static 图片 import 记录 var -> static 相对路径后删除；
        # @theme 组件 import（Tabs/TabItem）直接删除（组件语法由规则 7 消化）
        var_map = {}
        kept = []
        for ln in body.split("\n"):
            m = IMPORT_IMG_RE.match(ln)
            if m:
                var_map[m.group(1)] = m.group(2)
                continue
            if IMPORT_THEME_RE.match(ln):
                continue
            kept.append(ln)
        body = "\n".join(kept)

        # 正文第一个 H1：删除（title 已进 courses.json）
        lines = body.split("\n")
        inf = False
        for i, ln in enumerate(lines):
            if FENCE_RE.match(ln):
                inf = not inf
                continue
            if not inf and re.match(r"^#\s+\S", ln):
                lines = lines[:i] + lines[i + 1:]
                break

        converted = conv.convert("\n".join(lines), rel, slug, var_map)
        converted = conv.tidy(converted)
        content = "\n".join(converted) + "\n\n" + DEFAULT_ATTRIBUTION + "\n"
        entries.append((slug, title, content))
        print(f"    [{idx:3d}/{len(spec)}] {slug}  <-  docs/{rel}")

    # 图片复制/下载；下载失败的把 md 中相对路径回退为原 URL
    failed = collector.run()
    if failed:
        for i, (slug, title, content) in enumerate(entries):
            for key, url in failed.items():
                content = content.replace(
                    f"](images/{args.course_slug}/{key})", f"]({url})")
            entries[i] = (slug, title, content)

    # 幂等写出 md（UTF-8 无 BOM、LF）
    total_bytes = 0
    for slug, title, content in entries:
        encoded = content.encode("utf-8")
        (out_dir / f"{slug}.md").write_bytes(encoded)
        total_bytes += len(encoded)
        chapters.append({"slug": slug, "title": title, "sort_order": len(chapters) + 1,
                         "file": f"{slug}.md"})

    # courses.json：按 slug 原位替换（幂等），无则追加；既有课程文本一字不动
    json_path = out_dir / "courses.json"
    new_course = {
        "slug": args.course_slug,
        "title": args.course_title,
        "summary": args.summary,
        "language": args.language,
        "color": args.color,
        "sort_order": args.sort_order,
        "chapters": chapters,
    }
    action = update_courses_json(json_path, new_course)

    # 统计与告警
    print("\n===== 统计 =====")
    print(f"章节数: {len(chapters)}")
    print(f"输出总字节: {total_bytes}")
    print(collector.summary())
    for page, path in collector.missing_sources:
        print(f"  [缺失图片] {page}: static/{path}")
    if collector.failures:
        print(f"图片下载失败清单（{len(collector.failures)} 个，md 中保留原 URL）:")
        for url, err in collector.failures:
            print(f"  - {url}  ({err})")
    if conv.warnings:
        print(f"警告 {len(conv.warnings)} 条:")
        for w in conv.warnings:
            print(f"  - {w}")
    else:
        print("警告: 无")
    print(f"courses.json 已{action}课程 {args.course_slug}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
