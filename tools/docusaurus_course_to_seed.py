# courses.json 输出（文本级手术：只替换/追加本课程块，既有课程字节零改动）
# ---------------------------------------------------------------------------


def dump_course_block(course) -> str:
    """单个课程对象的文本块（4 空格缩进、章节单行对象，与既有文件风格一致）。"""
    parts = ["    {\n"]
    parts.append('      "slug": %s,\n' % json.dumps(course["slug"], ensure_ascii=False))
    parts.append('      "title": %s,\n' % json.dumps(course["title"], ensure_ascii=False))
    parts.append('      "summary": %s,\n' % json.dumps(course["summary"], ensure_ascii=False))
    parts.append('      "language": %s,\n' % json.dumps(course["language"], ensure_ascii=False))
    parts.append('      "color": %s,\n' % json.dumps(course["color"], ensure_ascii=False))
    parts.append('      "sort_order": %d,\n' % course["sort_order"])
    parts.append('      "chapters": [\n')
    chs = course["chapters"]
    for ki, ch in enumerate(chs):
        one = json.dumps(ch, ensure_ascii=False)
        comma = "," if ki < len(chs) - 1 else ""
        parts.append("        %s%s\n" % (one, comma))
    parts.append("      ]\n")
    parts.append("    }")
    return "".join(parts)


def update_courses_json(json_path: Path, new_course: dict) -> str:
    """按 slug 原位替换/追加课程块；返回动作描述。

    只改动本课程块的字节，既有课程文本一字不动（与 mdbook_trpl_to_seed.py
    的追加式写法一致，保证先于本脚本写入的内容字节级不变）。
    """
    suffix = "\n  ]\n}\n"
    if json_path.exists():
        text = json_path.read_text(encoding="utf-8")
    else:
        text = '{\n  "courses": [\n  ]\n}'
    data = json.loads(text)
    slug = new_course["slug"]
    block = dump_course_block(new_course)

    marker = '\n    {\n      "slug": %s,\n' % json.dumps(slug, ensure_ascii=False)
    if any(c.get("slug") == slug for c in data["courses"]):
        idx = text.find(marker)
        if idx < 0:
            sys.exit(f"courses.json 已含 {slug} 但无法定位其文本块，请人工检查")
        start = idx + 1  # '    {' 行首
        end = text.find("\n    }", idx)
        if end < 0:
            sys.exit(f"courses.json 中 {slug} 块缺少闭合 '    }}'")
        end += len("\n    }")
        text = text[:start] + block + text[end:]
        action = "原位替换"
    else:
        stem = text.rstrip("\n")
        tail = "\n  ]\n}"
        if not stem.endswith(tail):
            sys.exit("courses.json 结尾格式异常（应以 '\\n  ]\\n}\\n' 结束）")
        body = stem[: -len(tail)].rstrip()
        if body.endswith("["):  # 空课程列表：{"courses": [
            text = body + "\n" + block + tail + "\n"
        else:
            text = body + ",\n" + block + tail + "\n"
        action = "末尾追加"

    # 校验：JSON 合法、既有课程数据不变、章节数正确
    new_data = json.loads(text)
    old_by_slug = {c.get("slug"): c for c in data["courses"] if c.get("slug") != slug}
    new_old = [c for c in new_data["courses"] if c.get("slug") != slug]
    if new_old != [old_by_slug[c["slug"]] for c in new_old]:
        sys.exit("内部错误：既有课程数据被改动")
    mine = [c for c in new_data["courses"] if c.get("slug") == slug]
    if len(mine) != 1 or mine[0] != new_course:
        sys.exit("内部错误：新课程块写入不完整")
    json_path.write_bytes(text.encode("utf-8"))
    return action


