class ImageCollector:
    """登记图片目标，统一复制/下载；已存在的跳过（幂等）。"""

    def __init__(self, repo_root: Path, images_dir: Path, course_slug: str,
                 retries: int = 2, timeout: int = 30, workers: int = 8):
        self.repo_root = repo_root
        self.images_dir = images_dir / course_slug
        self.course_slug = course_slug
        self.retries = retries
        self.timeout = timeout
        self.workers = workers
        self.copies = {}   # dest_rel -> 源绝对路径
        self.downloads = {}  # dest_rel -> url
        self._copy_cache = {}    # (chapter, static_path) -> dest_rel（同源去重）
        self._download_cache = {}  # (chapter, url) -> dest_rel
        self.n_copied = 0
        self.n_copy_skipped = 0
        self.n_downloaded = 0
        self.n_download_skipped = 0
        self.n_failed = 0
        self.copy_bytes = 0
        self.download_bytes = 0
        self.failures = []  # (url, err)
        self.missing_sources = []  # (page, path)

    def _dedupe_name(self, chapter: str, name: str, taken: set) -> str:
        if f"{chapter}/{name}" not in taken:
            return name
        stem, dot, ext = name.rpartition(".")
        base = stem if dot else name
        ext = ("." + ext) if dot else ""
        n = 2
        while f"{chapter}/{base}-{n}{ext}" in taken:
            n += 1
        return f"{base}-{n}{ext}"

    def rel(self, chapter: str, name: str) -> str:
        return f"images/{self.course_slug}/{chapter}/{name}"

    def plan_copy(self, page: str, chapter: str, static_path: str, var: str):
        """登记一张 @site/static 图片：返回 md 相对路径（源缺失时返回 None）。"""
        cache_key = (chapter, static_path)
        if cache_key in self._copy_cache:
            return self._copy_cache[cache_key]
        src = self.repo_root / "static" / static_path
        if not src.is_file():
            self.missing_sources.append((page, static_path))
            return None
        name = src.name
        taken = {k for k in self.copies if k.startswith(chapter + "/")}
        taken |= {k for k in self.downloads if k.startswith(chapter + "/")}
        name = self._dedupe_name(chapter, name, taken)
        key = f"{chapter}/{name}"
        self.copies[key] = src
        rel = self.rel(chapter, name)
        self._copy_cache[cache_key] = rel
        return rel

    def plan_download(self, chapter: str, url: str) -> str:
        """登记一张远程图片：返回 md 相对路径。"""
        cache_key = (chapter, url)
        if cache_key in self._download_cache:
            return self._download_cache[cache_key]
        name = url_filename(url)
        taken = {k for k in self.copies if k.startswith(chapter + "/")}
        taken |= {k for k in self.downloads if k.startswith(chapter + "/")}
        name = self._dedupe_name(chapter, name, taken)
        key = f"{chapter}/{name}"
        self.downloads[key] = url
        rel = self.rel(chapter, name)
        self._download_cache[cache_key] = rel
        return rel

    WAYBACK_PREFIX = "https://web.archive.org/web/2023id_/"

    def _fetch_bytes(self, url: str) -> bytes:
        """下载一张图片：原址（UA 伪装 + 重试），失败回退 Wayback Machine。

        developer.android.com 的部分历史 GIF 已下架（404），
        web.archive.org/web/2023id_/<url> 重定向到最近快照，可取回原图。
        """
        last_err = None
        no_query = url.split("#", 1)[0].split("?", 1)[0]
        for url2 in (url, self.WAYBACK_PREFIX + url, self.WAYBACK_PREFIX + no_query):
            for attempt in range(self.retries + 1):
                try:
                    req = urllib.request.Request(url2, headers={
                        "User-Agent": USER_AGENT,
                        "Accept": "image/avif,image/webp,image/apng,image/*,*/*;q=0.8",
                        "Referer": urllib.parse.urlsplit(url).scheme + "://" +
                                   urllib.parse.urlsplit(url).netloc + "/",
                    })
                    with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                        return resp.read()
                except Exception as exc:  # noqa: BLE001 - 网络/404 等统一重试
                    last_err = exc
                    if attempt < self.retries:
                        time.sleep(1.5 * (attempt + 1))
        raise RuntimeError(str(last_err))

    def run(self) -> dict:
        """执行复制与下载；返回 {dest_rel: 原 url} 下载失败映射（供 md 回退）。"""
        for key, src in sorted(self.copies.items()):
            # key = "<chapter>/<name>"，dest = <images_dir>/<course>/<chapter>/<name>
            dest = self.images_dir / Path(key)
            if dest.exists() and dest.stat().st_size > 0:
                self.n_copy_skipped += 1
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)
            self.n_copied += 1
            self.copy_bytes += dest.stat().st_size

        failed = {}
        if self.downloads:
            items = sorted(self.downloads.items())

            def work(entry):
                key, url = entry
                dest = self.images_dir / Path(key)
                if dest.exists() and dest.stat().st_size > 0:
                    return ("skip", key, url, 0, None)
                try:
                    data = self._fetch_bytes(url)
                except Exception as exc:  # noqa: BLE001
                    return ("fail", key, url, 0, str(exc))
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(data)
                return ("ok", key, url, len(data), None)

            with ThreadPoolExecutor(max_workers=self.workers) as ex:
                for status, key, url, nbytes, err in ex.map(work, items):
                    if status == "ok":
                        self.n_downloaded += 1
                        self.download_bytes += nbytes
                    elif status == "skip":
                        self.n_download_skipped += 1
                    else:
                        self.n_failed += 1
                        failed[key] = url
                        self.failures.append((url, err))
        return failed

    def summary(self) -> str:
        return (f"图片: 本地复制 {self.n_copied}（跳过已存在 {self.n_copy_skipped}，"
                f"{self.copy_bytes} 字节）/ 下载 {self.n_downloaded}"
                f"（跳过已存在 {self.n_download_skipped}，{self.download_bytes} 字节）"
                f"/ 下载失败 {self.n_failed}")


